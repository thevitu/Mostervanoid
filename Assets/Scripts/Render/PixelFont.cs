        public static int TextWidth(string text, int scale) => text.Length * 6 * scale - scale;

        /// <summary>Desenha texto centralizado em (cx, cy) no array de pixels (origem embaixo-esquerda).</summary>
        public static void Draw(Color[] px, int w, int h, string text, int cx, int cy, int scale, Color col, Color? shadow = null)
        {
            text = text.ToUpperInvariant();
            int x0 = cx - TextWidth(text, scale) / 2;
            int y0 = cy - 7 * scale / 2;
            if (shadow.HasValue) DrawRaw(px, w, h, text, x0 + scale, y0 - scale, scale, shadow.Value);
            DrawRaw(px, w, h, text, x0, y0, scale, col);
        }

        static void DrawRaw(Color[] px, int w, int h, string text, int x0, int y0, int scale, Color col)
        {
            for (int i = 0; i < text.Length; i++)
            {
                if (!glyphs.TryGetValue(text[i], out var g)) continue;
                for (int row = 0; row < 7; row++)
                    for (int c = 0; c < 5; c++)
                    {
                        if (g[row][c] != '#') continue;
                        int gx = x0 + (i * 6 + c) * scale;
                        int gy = y0 + (6 - row) * scale;
                        for (int sy = 0; sy < scale; sy++)
                            for (int sx = 0; sx < scale; sx++)
                            {
                                int x = gx + sx, y = gy + sy;
                                if (x >= 0 && x < w && y >= 0 && y < h) px[y * w + x] = col;
                            }
                    }
            }
        }
    }
